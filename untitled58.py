import glob
IMG_SIZE   = 128
MAX_IMAGES = 600

all_images = glob.glob('/content/chest_xray/**/*.jpeg', recursive=True)
all_images = all_images[:MAX_IMAGES]
print(f"Loading {len(all_images)} images...")

images      = []
image_paths = []
labels      = []

for path in all_images:
    img = cv2.imread(path, cv2.IMREAD_GRAYSCALE)
    if img is not None:
        img = cv2.resize(img, (IMG_SIZE, IMG_SIZE))
        img = img / 255.0
        images.append(img.flatten())
        image_paths.append(path)
        label = 'PNEUMONIA' if 'PNEUMONIA' in path else 'NORMAL'
        labels.append(label)

images = np.array(images)
print(f"✓ Loaded {len(images)} images")
print(f"Normal:    {labels.count('NORMAL')}")
print(f"Pneumonia: {labels.count('PNEUMONIA')}")

# Chart 1 — Sample images
fig, axes = plt.subplots(2, 5, figsize=(15, 6))
fig.suptitle('Sample Chest X-Ray Images', fontsize=14, fontweight='bold')

normal_paths    = [p for p,l in zip(image_paths,labels) if l=='NORMAL'][:5]
pneumonia_paths = [p for p,l in zip(image_paths,labels) if l=='PNEUMONIA'][:5]

for i, path in enumerate(normal_paths):
    img = cv2.imread(path, cv2.IMREAD_GRAYSCALE)
    img = cv2.resize(img, (128,128))
    axes[0,i].imshow(img, cmap='gray')
    axes[0,i].set_title('NORMAL', color='green', fontweight='bold')
    axes[0,i].axis('off')

for i, path in enumerate(pneumonia_paths):
    img = cv2.imread(path, cv2.IMREAD_GRAYSCALE)
    img = cv2.resize(img, (128,128))
    axes[1,i].imshow(img, cmap='gray')
    axes[1,i].set_title('PNEUMONIA', color='red', fontweight='bold')
    axes[1,i].axis('off')

plt.tight_layout()
plt.show()

# Chart 2 — Distribution
fig, ax = plt.subplots(figsize=(8,5))
label_counts = pd.Series(labels).value_counts()
ax.bar(label_counts.index, label_counts.values,
       color=['#378ADD','#D85A30'], width=0.4)
ax.set_title('Dataset Distribution', fontsize=14, fontweight='bold')
ax.set_ylabel('Count')
for i,(label,count) in enumerate(label_counts.items()):
    ax.text(i, count+2, str(count), ha='center', fontweight='bold')
plt.tight_layout()
plt.show()
print("INSIGHT: Normal lungs appear clear. Pneumonia shows white patches.")

print("Running PCA...")
scaler     = StandardScaler()
images_scaled = scaler.fit_transform(images)

pca        = PCA(n_components=50, random_state=42)
images_pca = pca.fit_transform(images_scaled)

print(f"✓ PCA done")
print(f"Original shape:   {images.shape}")
print(f"PCA shape:        {images_pca.shape}")
print(f"Variance explained: {pca.explained_variance_ratio_.sum()*100:.1f}%")

fig, ax = plt.subplots(figsize=(10,5))
ax.plot(np.cumsum(pca.explained_variance_ratio_)*100,
        color='#378ADD', linewidth=2)
ax.axhline(y=80, color='#D85A30', linestyle='--', label='80% threshold')
ax.set_title('PCA — Cumulative Explained Variance', fontsize=14, fontweight='bold')
ax.set_xlabel('Number of Components')
ax.set_ylabel('Cumulative Explained Variance (%)')
ax.legend()
plt.tight_layout()
plt.show()

import umap as umap_lib

reducer      = umap_lib.UMAP(n_components=2, random_state=42,
                               n_neighbors=15, min_dist=0.1)
images_umap  = reducer.fit_transform(images_pca)
print("✓ UMAP done")

fig, ax = plt.subplots(figsize=(10,8))
colors  = ['#378ADD' if l=='NORMAL' else '#D85A30' for l in labels]
ax.scatter(images_umap[:,0], images_umap[:,1],
           c=colors, alpha=0.6, s=20)
ax.set_title('UMAP Projection of X-ray Images', fontsize=14, fontweight='bold')
ax.set_xlabel('UMAP 1'); ax.set_ylabel('UMAP 2')
from matplotlib.patches import Patch
ax.legend(handles=[Patch(facecolor='#378ADD', label='NORMAL'),
                   Patch(facecolor='#D85A30', label='PNEUMONIA')])
plt.tight_layout()
plt.show()
print("INSIGHT: UMAP separates normal and pneumonia into distinct clusters.")

print("Running K-Means...")
inertias = []
K_range  = range(2, 10)
for k in K_range:
    km = KMeans(n_clusters=k, random_state=42, n_init=10)
    km.fit(images_pca)
    inertias.append(km.inertia_)

fig, ax = plt.subplots(figsize=(10,5))
ax.plot(K_range, inertias, 'bo-', linewidth=2, markersize=8)
ax.set_title('K-Means Elbow Method', fontsize=14, fontweight='bold')
ax.set_xlabel('Number of Clusters (K)')
ax.set_ylabel('Inertia')
plt.tight_layout()
plt.show()

best_k    = 3
kmeans    = KMeans(n_clusters=best_k, random_state=42, n_init=10)
km_labels = kmeans.fit_predict(images_pca)
sil_score = silhouette_score(images_pca, km_labels)

print(f"✓ K-Means done — K={best_k}")
print(f"Silhouette Score: {sil_score:.4f}")
print(f"Cluster sizes: {pd.Series(km_labels).value_counts().to_dict()}")

fig, ax = plt.subplots(figsize=(10,8))
colors_km = ['#378ADD','#D85A30','#1D9E75']
for cluster in range(best_k):
    mask = km_labels == cluster
    ax.scatter(images_umap[mask,0], images_umap[mask,1],
               c=colors_km[cluster], alpha=0.6, s=20,
               label=f'Cluster {cluster}')
ax.set_title('K-Means Clusters on UMAP', fontsize=14, fontweight='bold')
ax.set_xlabel('UMAP 1'); ax.set_ylabel('UMAP 2')
ax.legend()
plt.tight_layout()
plt.show()
print(f"INSIGHT: K-Means found {best_k} natural clusters in X-ray data.")

print("Running Isolation Forest anomaly detection...")
iso_forest     = IsolationForest(contamination=0.1,
                                  random_state=42, n_estimators=100)
anomaly_labels = iso_forest.fit_predict(images_pca)
anomaly_scores = iso_forest.decision_function(images_pca)

n_anomalies = (anomaly_labels == -1).sum()
print(f"✓ Done")
print(f"Total images:      {len(anomaly_labels)}")
print(f"Anomalies detected:{n_anomalies} ({n_anomalies/len(anomaly_labels)*100:.1f}%)")

fig, ax = plt.subplots(figsize=(10,8))
normal_mask  = anomaly_labels == 1
anomaly_mask = anomaly_labels == -1
ax.scatter(images_umap[normal_mask,0], images_umap[normal_mask,1],
           c='#378ADD', alpha=0.4, s=15, label='Normal')
ax.scatter(images_umap[anomaly_mask,0], images_umap[anomaly_mask,1],
           c='#D85A30', alpha=0.8, s=60, label='Anomaly/Misplaced', marker='*')
ax.set_title('Anomaly Detection — Misplaced X-rays', fontsize=14, fontweight='bold')
ax.set_xlabel('UMAP 1'); ax.set_ylabel('UMAP 2')
ax.legend()
plt.tight_layout()
plt.show()
print("INSIGHT: Red stars = flagged misplaced or anomalous X-rays.")


unique_labels = sorted(set(db_labels))
cmap = plt.cm.tab10(np.linspace(0,1,max(len(unique_labels),2)))
for i, label in enumerate(unique_labels):
    mask = db_labels == label
    if label == -1:
        ax.scatter(images_umap[mask,0], images_umap[mask,1],
                   c='red', alpha=0.6, s=50, marker='x', label='Outliers')
    else:
        ax.scatter(images_umap[mask,0], images_umap[mask,1],
                   color=cmap[i], alpha=0.6, s=15,
                   label=f'Cluster {label}')
ax.set_title('DBSCAN Clustering on UMAP', fontsize=14, fontweight='bold')
ax.set_xlabel('UMAP 1'); ax.set_ylabel('UMAP 2')
ax.legend()

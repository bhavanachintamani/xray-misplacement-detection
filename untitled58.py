print("Detecting misplaced X-rays...")
misplaced_flags = []
for i in range(len(images)):
    risk = 0
    if anomaly_labels[i] == -1: risk += 2
    if db_labels[i] == -1:      risk += 1
    if anomaly_scores[i] < -0.1: risk += 1
    misplaced_flags.append(risk)

misplaced_flags = np.array(misplaced_flags)
high_risk = misplaced_flags >= 2

print(f"Total images:      {len(images)}")
print(f"High risk:         {high_risk.sum()} ({high_risk.sum()/len(images)*100:.1f}%)")
print(f"Low risk:          {(~high_risk).sum()}")

misplaced_indices = np.where(high_risk)[0][:6]
